/** 질문 → 가장 잘 맞는 답 (없으면 null) */
export function findAnswer(q: string): BotAnswer | null {
  const s = q.toLowerCase().replace(/\s+/g, '')
  let best: BotAnswer | null = null
  let score = 0
  for (const a of BOT_FAQ) {
    const n = a.keys.filter((k) => s.includes(k.toLowerCase())).length
    if (n > score) {
      score = n
      best = a
    }
  }
  return best
}

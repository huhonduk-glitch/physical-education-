export interface WorkSrc {
  doc: WorkDoc
  /** 쪽 (하나 또는 시작~끝) */
  page: number | [number, number]
}

export interface WorkLine {
  text: string
  src: WorkSrc
  /** 제주교육청 2026 기준 (다른 시도는 다를 수 있음) */
  local?: boolean
}

export interface WorkMenu {
  id: string
  title: string
  /** 나이스 화면 위쪽 경로 (화면 캡처 그대로) */
  path: string[]
  /** 누가 하는지 (없으면 담당 교사) */
  who?: string
  steps: WorkLine[]
  tips?: WorkLine[]
}

/** 꼭 받아야 하는 교육 (원문의 '의무' · '필수' · '선택' 표시를 그대로 옮긴다 — 2026-11-11 교사 요청) */
export interface WorkTraining {
  name: string
  /** 원문 표시: 법적 의무(64쪽 '법적 의무교육' 표) · 의무(본문에 의무 · 필수 · 실시) · 선택(표에 '선택') */
  kind: '법적 의무' | '의무' | '선택'
  who: string
  /** 횟수 · 시간 */
  times: string
  /** 원문에 적힌 관련 근거 (없으면 비움) */
  basis?: string
  /** 어디서 · 어떻게 */
  how?: string
  src: WorkSrc
  local?: boolean
}

export interface WorkTopic {
  id: 'team' | 'club' | 'committee'
  title: string
  summary: string
  calendar: { when: string; what: string; src: WorkSrc; local?: boolean }[]
  menus: WorkMenu[]
  rules: { title: string; lines: WorkLine[] }[]
  forms: WorkLine[]
  /** 꼭 받아야 하는 교육 (운동부) */
  trainings?: WorkTraining[]
  /** 교육 탭 아래 알아 둘 것 */
  trainingNotes?: WorkLine[]
  /** 양식 탭의 묶음별 서류 (교육청 제출 서식 · 학교에서 갖춰 두는 서류) */
  formGroups?: { title: string; lines: WorkLine[] }[]
}

